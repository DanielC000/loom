// What opened each agent turn, read off the user-role turn that started it (card 7627a850). The
// session MCP strip shows it as "Turn 16 · after your message" / "after worker report 9e40d7a1".
// Pure and JSX-free, pinned by test/turn-cause.mjs.
//
// The tag vocabulary is the daemon's own `[loom:<tag>]` frames (grep `\[loom:` in packages/daemon/src):
// a worker report is `[loom:worker-report] worker <id> (task <id>) — <status>: <summary>`
// (sessions/service.ts), manager direction is `[loom:from-manager]\n<text>` (frameFromManager). A turn
// Loom delivered whole arrives wrapped in `<pasted_content id="…">…</pasted_content id="…">`, so the
// wrapper is seen through before classifying. Every string here is transcript text: callers render it
// as React text only, never as HTML.
import type { TranscriptTurn } from "./api";

export type TurnCauseKind =
  | "human" | "opening" | "worker-report" | "direction" | "merge" | "gate" | "wake" | "continuation" | "engine" | "other";

export interface TurnCause {
  kind: TurnCauseKind;
  /** Reads after "after ": "your message", "worker report", "a merge result". */
  label: string;
  /** An id or tag set in mono after the label (a worker's short id, an unknown tag's name), or "". */
  id: string;
  /** A qualifier shown in parentheses, e.g. a worker report's status, or "". */
  detail: string;
  /** The message body, whitespace collapsed and cut to EXCERPT_MAX characters. Plain text. */
  excerpt: string;
  /** Further Loom frames coalesced into the same turn after the first one. */
  more: number;
}

export const EXCERPT_MAX = 80;

const PASTED_OPEN = /^\s*<pasted_content id="[0-9A-Za-z]+">\r?\n?/;
const PASTED_CLOSE = /\r?\n?<\/pasted_content id="[0-9A-Za-z]+">\s*$/;
const POSSIBLE_DUPLICATE = /^\[loom:possible-duplicate root:[0-9a-f]{8}\] /;
/** `[loom:<tag>]` or `[loom:<tag>:<suffix>]` at the very start of the text. */
const LEAD_TAG = /^\[loom:([a-z][a-z0-9-]*)(?::([a-z0-9-]+))?\]/;
const FRAME_LINE = /^\[loom:[a-z][a-z0-9-]*(?::[a-z0-9-]+)?\]/gm;
const WORKER_REPORT = /^ worker ([0-9A-Za-z-]+)(?: \(task [^)]*\))? — ([a-z]+)(?::\s*([\s\S]*))?/;

/** The text Loom actually framed: a pasted_content wrapper and a possible-duplicate prefix removed. */
export function unwrapTurnText(text: string): string {
  let s = text;
  if (PASTED_OPEN.test(s)) s = s.replace(PASTED_OPEN, "").replace(PASTED_CLOSE, "");
  return s.trim().replace(POSSIBLE_DUPLICATE, "");
}

export function excerptOf(text: string, max = EXCERPT_MAX): string {
  const s = text.replace(/\s+/g, " ").trim();
  return s.length > max ? `${s.slice(0, max - 1)}…` : s;
}

const shortId = (v: string): string => (/^[0-9a-f]{8}-[0-9a-f-]{27,}$/i.test(v) ? v.slice(0, 8) : v);

/** Tagged frames, in the order they are checked. A tag matches by exact name or, ending in "-", by prefix. */
const TAG_CLASSES: ReadonlyArray<{ tags: readonly string[]; kind: TurnCauseKind; label: string }> = [
  { tags: ["from-manager"], kind: "direction", label: "manager direction" },
  { tags: ["from-platform"], kind: "direction", label: "a Platform Lead message" },
  { tags: ["from-auditor"], kind: "direction", label: "an auditor message" },
  { tags: ["from-assistant"], kind: "direction", label: "an assistant message" },
  { tags: ["from-owner-via-companion"], kind: "human", label: "your message, via the companion" },
  { tags: ["merge-", "already-merged"], kind: "merge", label: "a merge result" },
  { tags: ["gate-", "dist-importer-check"], kind: "gate", label: "a gate result" },
  { tags: ["wake"], kind: "wake", label: "a scheduled wake" },
  { tags: ["reminder"], kind: "wake", label: "a reminder" },
  { tags: ["idle", "worker-idle"], kind: "wake", label: "an idle nudge" },
  { tags: ["heartbeat"], kind: "wake", label: "a heartbeat" },
  { tags: ["poll"], kind: "wake", label: "a poll result" },
  { tags: ["continuation", "handoff", "inherited-by-recycle"], kind: "continuation", label: "a continuation note" },
  { tags: ["daemon-restarted", "crash-recovered", "auto-recovered"], kind: "continuation", label: "a restart notice" },
];

/** Claude Code's own user-role entries: not a person, not Loom. */
const ENGINE_NOTES: ReadonlyArray<[RegExp, string]> = [
  [/^Base directory for this skill:/, "a skill load"],
  [/^<command-name>|^<local-command-|^Caveat: The messages below were generated by the user while running local commands/, "a slash command"],
  [/^<task-notification>/, "a background task notice"],
  [/^\[Request interrupted/, "an interrupt"],
];

/**
 * Classify the user-role turn that opened an agent turn. `isFirst` marks the session's first user turn:
 * untagged, that is the opening prompt (a kickoff, or a person's first message); untagged later, it
 * is a person typing into the composer.
 */
export function classifyTurnOpener(text: string, isFirst: boolean): TurnCause {
  const s = unwrapTurnText(text);
  const frames = s.match(FRAME_LINE)?.length ?? 0;
  const base = { id: "", detail: "", more: 0 };

  const m = LEAD_TAG.exec(s);
  if (m) {
    const tag = m[1]!;
    const suffix = m[2] ?? "";
    const rest = s.slice(m[0].length);
    const more = Math.max(0, frames - 1);
    if (tag === "worker-report") {
      const r = WORKER_REPORT.exec(rest);
      return {
        kind: "worker-report", label: "worker report", id: r ? shortId(r[1]!) : "", detail: r?.[2] ?? "",
        excerpt: excerptOf(r?.[3] ?? rest), more,
      };
    }
    const cls = TAG_CLASSES.find((c) => c.tags.some((t) => (t.endsWith("-") ? tag.startsWith(t) : tag === t)));
    if (cls) {
      const label = cls.kind === "direction" && suffix === "redirect" ? "a redirect" : cls.label;
      return { ...base, kind: cls.kind, label, excerpt: excerptOf(rest), more };
    }
    return { ...base, kind: "other", label: "another Loom notice", id: tag, excerpt: excerptOf(rest), more };
  }
  if (s.startsWith("[loom:")) return { ...base, kind: "other", label: "another Loom notice", excerpt: excerptOf(s) };

  for (const [re, label] of ENGINE_NOTES) {
    if (re.test(s)) return { ...base, kind: "engine", label, excerpt: "" };
  }
  return isFirst
    ? { ...base, kind: "opening", label: "the opening prompt", excerpt: excerptOf(s) }
    : { ...base, kind: "human", label: "your message", excerpt: excerptOf(s) };
}

/**
 * Turn number → what opened it. Numbered exactly as parseMcpCalls numbers a call's turn (the count of
 * user-role turns seen so far), so turn N's opener is the Nth user-role turn. Turn 0 has none.
 */
export function turnCauses(turns: readonly TranscriptTurn[]): Map<number, TurnCause> {
  const out = new Map<number, TurnCause>();
  let n = 0;
  for (const t of turns) {
    if (t.role !== "user") continue;
    n++;
    out.set(n, classifyTurnOpener(t.text, n === 1));
  }
  return out;
}

/** The cause as one plain sentence fragment: "after worker report 9e40d7a1 (progress)". */
export function causeText(c: TurnCause): string {
  return [
    `after ${c.label}`,
    c.id,
    c.detail ? `(${c.detail})` : "",
    c.more > 0 ? `+${c.more} more` : "",
  ].filter(Boolean).join(" ");
}
